-- ============================================================
-- V5 — Dispositivos para notificaciones push (app móvil)
--
-- Motivación:
--   La app móvil avisa a los coordinadores de colegio (rol
--   INSTITUCION) cuando su pedido pasa a LISTO_PARA_ENTREGA,
--   usando Firebase Cloud Messaging. Cada dispositivo registra
--   aquí su token al iniciar sesión y lo elimina al cerrarla.
--
--   Tabla nueva: no modifica ninguna tabla existente.
--   Entidad: DispositivoNotificacion (ddl-auto=validate en prod).
-- ============================================================

CREATE TABLE IF NOT EXISTS dispositivos_notificacion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL,
    token       VARCHAR(512) NOT NULL,
    plataforma  VARCHAR(20)  NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_dispositivo_token UNIQUE (token),
    CONSTRAINT ck_dispositivo_plataforma CHECK (plataforma IN ('ANDROID', 'IOS', 'WEB')),
    -- Si se elimina el usuario, sus dispositivos dejan de tener sentido.
    CONSTRAINT fk_dispositivo_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id) ON DELETE CASCADE
);

-- Búsqueda de los dispositivos de un usuario.
CREATE INDEX IF NOT EXISTS idx_dispositivo_usuario
    ON dispositivos_notificacion (usuario_id);
